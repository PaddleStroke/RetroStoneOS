double bench_flat_fraction(const uint8_t *rgb, int w, int h)
{
	static uint32_t hist[4096];
	uint32_t max = 0;
	size_t n = (size_t)w * (size_t)h;

	if (!rgb || !n)
		return 1.0;
	memset(hist, 0, sizeof(hist));
	for (size_t i = 0; i < n; i++) {
		unsigned k = (unsigned)(rgb[3 * i] >> 4) << 8 | (unsigned)(rgb[3 * i + 1] >> 4) << 4 |
			     (unsigned)(rgb[3 * i + 2] >> 4);

		if (++hist[k] > max)
			max = hist[k];
	}
	return (double)max / (double)n;
}

int bench_filter_args(int argc, char *const *argv, bool for_step, const char **out, int max)
{
	static const char *const drop1[] = { "--load-state", "--load-state-file", "--bench-start",
					     "--bench-report", "--bench-driver" };
	static const char *const drop1_step[] = { "--status-fd", "--poweroff-cmd", "--dump", "--menu-shot" };
	int n = 0;

	for (int i = 0; i < argc; i++) {
		const char *a = argv[i];
		bool skip = false;

		if (!strcmp(a, "--bench-step")) {
			i += 2;
			continue;
		}
		for (size_t k = 0; k < sizeof(drop1) / sizeof(drop1[0]); k++)
			skip |= !strcmp(a, drop1[k]);
		for (size_t k = 0; for_step && k < sizeof(drop1_step) / sizeof(drop1_step[0]); k++)
			skip |= !strcmp(a, drop1_step[k]);
		if (skip) {
			i++;
			continue;
		}
		if (for_step && (!strcmp(a, "--test-states") || !strcmp(a, "--bench-auto-apply")))
			continue;
		if (n < max - 1)
			out[n++] = a;
	}
	out[n] = NULL;
	return n;
}

void bench_safe_name(const char *in, char *out, size_t n)
{
	size_t k = 0;
	bool us = false;

	if (!n)
		return;
	for (; *in && k + 1 < n; in++) {
		unsigned char ch = (unsigned char)*in;

		if ((ch >= '0' && ch <= '9') || (ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || ch == '-') {
			out[k++] = (char)ch;
			us = false;
		} else if (!us && k > 0) {
			out[k++] = '_';
			us = true;
		}
	}
	while (k > 0 && out[k - 1] == '_')
		k--;
	out[k] = 0;
	if (!k)
		hstrlcpy(out, "game", n);
}

