int bench_write_keys(const char *path, const char *header, const struct bench_kv *kv, int n)
{
	struct ini old = { 0 };
	struct sbuf s;
	char *buf;
	size_t size = 8192;
	int r;

	/* never rewrite a file we could not read (only "no file yet" is empty) */
	r = ini_load(&old, path);
	if (r < 0 && r != -ENOENT) {
		hlog(HLOG_ERROR, "%s: cannot read (%s): not rewritten", path, strerror(-r));
		ini_free(&old);
		return r;
	}
	for (int i = 0; i < old.n; i++)
		size += strlen(old.e[i].key) + strlen(old.e[i].value) + 8;
	buf = malloc(size);
	if (!buf) {
		ini_free(&old);
		return -ENOMEM;
	}
	s = (struct sbuf){ buf, size, 0 };
	buf[0] = 0;
	sb_printf(&s, "%s\n", header ? header : "; RetroStoneOS core options");
	for (int i = 0; i < old.n; i++) {
		bool replaced = false;

		for (int k = 0; k < n; k++)
			replaced |= !strcasecmp(old.e[i].key, kv[k].key);
		if (!replaced)
			sb_printf(&s, "%s = \"%s\"\n", old.e[i].key, old.e[i].value);
	}
	for (int k = 0; k < n; k++)
		sb_printf(&s, "%s = \"%s\"\n", kv[k].key, kv[k].value);
	ini_free(&old);
	r = hwrite_atomic(path, buf, s.len, false);
	free(buf);
	return r;
}

int bench_ini_set_file(const char *path, const char *section, const char *key, const char *value)
{
	struct ini ini = { 0 };
	const char **secs;
	int nsec = 0, r;
	size_t size = 4096;
	char *buf;
	struct sbuf s;

	/* Review F-M9: a read error used to rewrite cores.ini with only the
	 * new key, and sections past the 64th were dropped. */
	r = ini_load(&ini, path);
	if (r < 0 && r != -ENOENT) {
		hlog(HLOG_ERROR, "%s: cannot read (%s): not rewritten", path, strerror(-r));
		ini_free(&ini);
		return r;
	}
	if (ini_set(&ini, section, key, value) < 0) {
		ini_free(&ini);
		return -ENOMEM;
	}
	secs = malloc(sizeof(*secs) * (size_t)(ini.n + 1));
	if (!secs) {
		ini_free(&ini);
		return -ENOMEM;
	}
	for (int i = 0; i < ini.n; i++) {
		bool seen = false;

		size += strlen(ini.e[i].section) + strlen(ini.e[i].key) + strlen(ini.e[i].value) + 16;
		for (int k = 0; k < nsec && !seen; k++)
			seen = !strcmp(secs[k], ini.e[i].section);
		if (!seen)
			secs[nsec++] = ini.e[i].section;
	}
	buf = malloc(size);
	if (!buf) {
		free(secs);
		ini_free(&ini);
		return -ENOMEM;
	}
	s = (struct sbuf){ buf, size, 0 };
	buf[0] = 0;
	/* the top-level keys first, then each section in order */
	for (int pass = 0; pass < 2; pass++)
		for (int k = 0; k < nsec; k++) {
			if ((pass == 0) != (secs[k][0] == 0))
				continue;
			if (secs[k][0])
				sb_printf(&s, "%s[%s]\n", s.len ? "\n" : "", secs[k]);
			for (int i = 0; i < ini.n; i++)
				if (!strcmp(ini.e[i].section, secs[k]))
					sb_printf(&s, "%s = \"%s\"\n", ini.e[i].key, ini.e[i].value);
		}
	r = hwrite_atomic(path, buf, s.len, true);   /* cores.ini.bak: coreinfo_pick() fallback */
	free(buf);
	free(secs);
	ini_free(&ini);
	return r;
}

int bench_apply(const struct bench_config *c, const char *user_dir, const char *game,
		const char *choices_path, const char *system, const char *rom_stem,
		const char *current_core)
{
	char path[BENCH_PATH], dir[BENCH_PATH], hdr[200];
	int r;

	if (!hpath(dir, sizeof(dir), "%s/%s", user_dir, c->core) ||
	    !hpath(path, sizeof(path), "%s/%s.ini", dir, game))
		return -ENAMETOOLONG;
	hmkdir_p(dir, 0755);
	snprintf(hdr, sizeof(hdr), "; RetroStoneOS core options (%s), benchmark choice \"%s\"", c->core, c->id);
	r = bench_write_keys(path, hdr, c->kv, c->nkv);
	if (r)
		return r;
	if (choices_path && current_core && strcmp(c->core, current_core) != 0) {
		char sec[512];

		if (!hpath(sec, sizeof(sec), "%s/%s", system, rom_stem))
			return -ENAMETOOLONG;
		r = bench_ini_set_file(choices_path, sec, "core", c->core);
	}
	return r;
}
